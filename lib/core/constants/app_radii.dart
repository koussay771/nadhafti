/// Nadhafti Design Token — Border Radii
/// "High Circularity" shape language from Stitch design system.
abstract final class AppRadii {
  /// 4px — smallest container elements
  static const double sm = 4.0;

  /// 8px — default card corner radius
  static const double md = 8.0;

  /// 12px — xl in Stitch
  static const double lg = 12.0;

  /// 16px — main content cards, modals
  static const double xl = 16.0;

  /// 24px — large modal sheets
  static const double xxl = 24.0;

  /// 9999px — pill-shaped buttons, chips, inputs
  static const double full = 999.0;
}
